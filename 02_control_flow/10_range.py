# ==========================================
# 10 - Control Flow: range()
# ==========================================

# ------------------------------------------
# 1. range(stop)
# ------------------------------------------

for number in range(5):
    print(number)

print()

# ------------------------------------------
# 2. range(start, stop)
# ------------------------------------------

for number in range(1, 6):
    print(number)

print()

# ------------------------------------------
# 3. range(start, stop, step)
# ------------------------------------------

for number in range(2, 11, 2):
    print(number)

print()

# ------------------------------------------
# 4. Counting backwards
# ------------------------------------------

for number in range(10, 0, -1):
    print(number)