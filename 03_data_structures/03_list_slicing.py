# ==========================================
# 03 - Data Structures: List Slicing
# ==========================================

fruits = ["apple", "banana", "orange", "mango", "grapes"]

# Basic slicing
print(fruits[1:4])

# From the beginning
print(fruits[:3])

# Until the end
print(fruits[2:])

# Copy the entire list
print(fruits[:])

# Using a step
print(fruits[::2])

# Reverse the list
print(fruits[::-1])