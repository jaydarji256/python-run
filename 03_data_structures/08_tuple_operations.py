# ==========================================
# 08 - Data Structures: Tuple Operations
# ==========================================

numbers = (10, 20, 30, 20, 40, 20)

# ------------------------------------------
# 1. Length
# ------------------------------------------

print("Length:", len(numbers))


# ------------------------------------------
# 2. Count
# ------------------------------------------

print("20 appears:", numbers.count(20), "times")


# ------------------------------------------
# 3. Index
# ------------------------------------------

print("Index of 30:", numbers.index(30))


# ------------------------------------------
# 4. Membership
# ------------------------------------------

print("Is 40 present?", 40 in numbers)
print("Is 100 present?", 100 in numbers)


# ------------------------------------------
# 5. Concatenation
# ------------------------------------------

tuple_a = (1, 2, 3)
tuple_b = (4, 5, 6)

combined = tuple_a + tuple_b

print("Combined:", combined)


# ------------------------------------------
# 6. Repetition
# ------------------------------------------

repeated = ("Python",) * 3

print("Repeated:", repeated)


# ------------------------------------------
# 7. Slicing
# ------------------------------------------

values = (10, 20, 30, 40, 50)

print("Slice:", values[1:4])


# ------------------------------------------
# 8. Looping
# ------------------------------------------

for value in values:
    print(value)