# ==========================================
# 05 - Type Casting
# ==========================================

# String -> Integer

age = "20"

print(age)
print(type(age))

age = int(age)

print(age)
print(type(age))


# Integer -> Float

number = 10

number = float(number)

print(number)
print(type(number))


# Integer -> String

number = 100

text = str(number)

print(text)
print(type(text))


# Float -> Integer

price = 99.99

price = int(price)

print(price)
print(type(price))


# String -> Float

marks = "85.5"

marks = float(marks)

print(marks)
print(type(marks))